import { fileURLToPath } from "node:url";

import { SKILL } from "#/cases/analyzing-recent-project-state.ts";
import { evalModel } from "#/orchestration/configuration.ts";
import type { AttemptResult, Result, Status } from "#/orchestration/verdict.ts";

export const REPORT_PATH = fileURLToPath(
  new URL("../../report.md", import.meta.url),
);

const MS_PER_SECOND = 1000;
const COST_DECIMALS = 2;
const WHOLE_SECONDS = 0;
const INITIAL_TOTAL = 0;
const NO_SCORED_RESULTS = 0;
const NO_ATTEMPTS_RUN = 0;

/** A cell with nothing to measure: the score and runs of a NOT_RUN row. */
const EMPTY_CELL = "—";

/** The runner's per-attempt stdout progress line. */
export function formatResultLine(attemptResult: AttemptResult): string {
  return `${attemptResult.status} ${(attemptResult.durationMs / MS_PER_SECOND).toFixed(WHOLE_SECONDS)}s $${attemptResult.costUsd.toFixed(COST_DECIMALS)}`;
}

/** The runner's per-case summary line, printed after the last attempt. */
export function formatCaseResultLine(result: Result): string {
  if (result.score === null) return result.status;
  return `${result.status} score ${result.score} (${result.attemptsPassed}/${result.attemptsRun} passed) ${(result.durationMs / MS_PER_SECOND).toFixed(WHOLE_SECONDS)}s $${result.costUsd.toFixed(COST_DECIMALS)}`;
}

/** A `|` would split a table column and a line ending would end the row. */
function escapeCell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll(/\r\n?|\n/g, " ");
}

function isScored(result: Result): result is Result & { score: number } {
  return result.score !== null;
}

function formatMeanScore(reportResults: Result[]): string {
  const scoredResults = reportResults.filter(isScored);
  if (scoredResults.length === NO_SCORED_RESULTS) return EMPTY_CELL;
  const scoreTotal = scoredResults.reduce(
    (total, result) => total + result.score,
    INITIAL_TOTAL,
  );
  return `${Math.round(scoreTotal / scoredResults.length)}`;
}

export function renderReport(reportResults: Result[]): string {
  const countByStatus = (status: Status) =>
    reportResults.filter((result) => result.status === status).length;
  const totalCostUsd = reportResults.reduce(
    (total, result) => total + result.costUsd,
    INITIAL_TOTAL,
  );
  const totalDurationSeconds = Math.round(
    reportResults.reduce(
      (total, result) => total + result.durationMs,
      INITIAL_TOTAL,
    ) / MS_PER_SECOND,
  );
  const generatedAt = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");

  const reportRows = reportResults
    .map((result) => {
      const scoreCell = result.score === null ? EMPTY_CELL : `${result.score}`;
      const runsCell =
        result.attemptsRun === NO_ATTEMPTS_RUN
          ? EMPTY_CELL
          : `${result.attemptsPassed}/${result.attemptsRun}`;
      return `| ${result.id} | ${result.tier} | ${result.status} | ${scoreCell} | ${runsCell} | ${escapeCell(result.observed)} |`;
    })
    .join("\n");

  return `# Eval Report — ${SKILL}

Generated by \`node evals/src/orchestration/run.ts\`. Rewritten every run and committed, so a
behavior change shows up as a diff.

Run: ${generatedAt} · ${reportResults.length} cases · ${countByStatus("PASS")} pass · ${countByStatus("DEGRADED")} degraded · ${countByStatus("FAIL")} fail · ${countByStatus("NOT_RUN")} not run · mean score ${formatMeanScore(reportResults)} · $${totalCostUsd.toFixed(COST_DECIMALS)} · ${totalDurationSeconds}s · model \`${evalModel}\`

| Case | Tier | Status | Score | Runs | Observed |
| ---- | ---- | ------ | ----- | ---- | -------- |
${reportRows}

Score is the percent of a case's attempts whose check passed; Runs shows the
underlying passed/run counts. PASS means every attempt passed, FAIL none, and
DEGRADED a mix — a flakiness signal, and it fails the run like FAIL does.
NOT_RUN rows were not executed by this run and carry no score. Tier 1 cases
are budget-capped and assert only the routing decision; tier 2 cases are full
behavioral runs.
`;
}
