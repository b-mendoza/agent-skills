import { fileURLToPath } from "node:url";

import { SKILL } from "#/cases/analyzing-recent-project-state.ts";
import { evalModel } from "#/orchestration/case-execution/model-configuration.ts";

export const REPORT_PATH = fileURLToPath(
  new URL("../../report.md", import.meta.url),
);

const MS_PER_SECOND = 1000;
const COST_DECIMALS = 2;
const WHOLE_SECONDS = 0;

type Status = "PASS" | "FAIL";
/** Case tiers as they appear in the report; `2*` is the derived row. */
export type ReportTier = "1" | "2" | "2*";

export interface Result {
  id: string;
  tier: ReportTier;
  status: Status;
  observed: string;
  costUsd: number;
  durationMs: number;
}

/** The runner's per-case stdout progress line. */
export function formatResultLine(result: Result): string {
  return `${result.status} ${(result.durationMs / MS_PER_SECOND).toFixed(WHOLE_SECONDS)}s $${result.costUsd.toFixed(COST_DECIMALS)}`;
}

/** A `|` would split a table column and a line ending would end the row. */
function escapeCell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll(/\r\n?|\n/g, " ");
}

export function renderReport(reportResults: Result[]): string {
  const passedCount = reportResults.filter(
    (result) => result.status === "PASS",
  ).length;
  const failedCount = reportResults.filter(
    (result) => result.status === "FAIL",
  ).length;
  const totalCostUsd = reportResults.reduce(
    (total, result) => total + result.costUsd,
    0,
  );
  const totalDurationSeconds = Math.round(
    reportResults.reduce((total, result) => total + result.durationMs, 0) /
      MS_PER_SECOND,
  );
  const generatedAt = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");

  const reportRows = reportResults
    .map(
      (result) =>
        `| ${result.id} | ${result.tier} | ${result.status} | ${escapeCell(result.observed)} |`,
    )
    .join("\n");

  return `# Eval Report — ${SKILL}

Generated by \`node evals/src/orchestration/run.ts\`. Rewritten every run and committed, so a
behavior change shows up as a diff.

Run: ${generatedAt} · ${reportResults.length} cases · ${passedCount} pass · ${failedCount} fail · $${totalCostUsd.toFixed(COST_DECIMALS)} · ${totalDurationSeconds}s · model \`${evalModel}\`

| Case | Tier | Result | Observed |
| ---- | ---- | ------ | -------- |
${reportRows}

Tier 1 cases are budget-capped and assert only the routing decision. Tier 2
cases are full behavioral runs. Every case listed here was executed; this report
records only observed results.
`;
}
