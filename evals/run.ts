#!/usr/bin/env node
// Entry point for the local eval suite.
//
//   node evals/run.ts                    every case
//   node evals/run.ts --tier=1           routing cases only (fast, cents)
//   node evals/run.ts --case=path-error  one case
//
// Cases run sequentially: they spend real tokens and the wall-clock cost of
// parallelism is not worth the token burn on a suite this small.

import { writeFileSync, readFileSync } from "node:fs";
import { makeFixture } from "./fixtures.ts";
import { runClaude, type Observation } from "./harness.ts";
import {
  SKILL,
  cases,
  checkMutationScope,
  type EvalCase,
} from "./cases/analyzing-recent-project-state.ts";

const REPORT_PATH = new URL("./report.md", import.meta.url).pathname;
const MANUAL_PATH = new URL(
  "./manual/analyzing-recent-project-state.md",
  import.meta.url,
).pathname;
const MODEL = process.env.EVAL_MODEL ?? "haiku";

interface Result {
  id: string;
  tier: string;
  status: "PASS" | "FAIL";
  observed: string;
  costUsd: number;
  durationMs: number;
}

type ManualCase = { id: string; reason: string };

function parseArgs(argv: string[]): { tier?: number; caseId?: string } {
  const out: { tier?: number; caseId?: string } = {};
  for (const arg of argv) {
    const tier = arg.match(/^--tier=(\d+)$/);
    if (tier) out.tier = Number(tier[1]);
    const caseId = arg.match(/^--case=(.+)$/);
    if (caseId) out.caseId = caseId[1];
  }
  return out;
}

/** Runs a check, turning a thrown assertion into a FAIL row. */
function evaluate(check: () => string): {
  status: "PASS" | "FAIL";
  observed: string;
} {
  let status: "PASS" | "FAIL" = "PASS";
  let observed = "";
  try {
    observed = check();
  } catch (err) {
    status = "FAIL";
    observed = (err as Error).message.split("\n")[0].slice(0, 160);
  }
  return { status, observed };
}

/** Case ids listed in the manual doc's tables, for the report's MANUAL rows. */
function manualCases(): ManualCase[] {
  const md = readFileSync(MANUAL_PATH, "utf8");
  const found: ManualCase[] = [];
  let heading = "";
  for (const line of md.split("\n")) {
    const h = line.match(/^##\s+(.*)$/);
    if (h) heading = h[1].trim();
    const row = line.match(/^\|\s*`([a-z0-9-]+)`\s*\|/i);
    if (row && !heading.startsWith("Automated")) {
      found.push({ id: row[1], reason: heading });
    }
  }
  return found;
}

async function runCase(c: EvalCase): Promise<[Result, Observation]> {
  const fx = makeFixture(c.fixture, SKILL);
  try {
    const observation = await runClaude({
      cwd: fx.cwd,
      gitRepo: fx.gitRepo || fx.cwd,
      prompt: c.prompt({
        missingPath: fx.missingPath,
        notGitPath: fx.notGitPath,
      }),
      budgetUsd: c.budgetUsd,
      model: MODEL,
      wallClockMs: c.wallClockMs,
    });

    const { status, observed } = evaluate(() => c.check(observation));

    return [
      {
        id: c.id,
        tier: String(c.tier),
        status,
        observed,
        costUsd: observation.costUsd,
        durationMs: observation.durationMs,
      },
      observation,
    ];
  } finally {
    fx.cleanup();
  }
}

function renderReport(results: Result[], manual: ManualCase[]): string {
  const pass = results.filter((r) => r.status === "PASS").length;
  const fail = results.filter((r) => r.status === "FAIL").length;
  const cost = results.reduce((s, r) => s + r.costUsd, 0);
  const secs = Math.round(results.reduce((s, r) => s + r.durationMs, 0) / 1000);
  const stamp = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");

  const rows = results
    .map(
      (r) =>
        `| ${r.id} | ${r.tier} | ${r.status} | ${r.observed} |`,
    )
    .join("\n");

  const manualRows = manual
    .map((m) => `| ${m.id} | — | MANUAL | ${m.reason} |`)
    .join("\n");

  return `# Eval Report — ${SKILL}

Generated by \`node evals/run.ts\`. Rewritten every run and committed, so a
behavior change shows up as a diff.

Run: ${stamp} · ${results.length} automated · ${pass} pass · ${fail} fail · ${manual.length} manual · $${cost.toFixed(2)} · ${secs}s · model \`${MODEL}\`

| Case | Tier | Result | Observed |
| ---- | ---- | ------ | -------- |
${rows}
${manualRows}

Tier 1 cases are budget-capped and assert only the routing decision. Tier 2
cases are full behavioral runs. \`MANUAL\` rows are defined in
[\`manual/${SKILL}.md\`](./manual/${SKILL}.md) and were **not executed** — they
are listed so an unrun expectation is never mistaken for a passing one.
`;
}

async function main(): Promise<void> {
  const { tier, caseId } = parseArgs(process.argv.slice(2));
  const selected = cases.filter(
    (c) =>
      (tier === undefined || c.tier === tier) && (!caseId || c.id === caseId),
  );

  if (selected.length === 0) {
    console.error("No cases matched.");
    process.exit(2);
  }

  const results: Result[] = [];
  const behavioral: Observation[] = [];

  for (const c of selected) {
    process.stdout.write(`· ${c.id} (tier ${c.tier}) ... `);
    const [result, observation] = await runCase(c);
    if (c.tier === 2) behavioral.push(observation);
    results.push(result);
    console.log(
      `${result.status} ${(result.durationMs / 1000).toFixed(0)}s $${result.costUsd.toFixed(2)}`,
    );
    if (result.status === "FAIL") console.log(`    ${result.observed}`);
  }

  // Derived from the tier-2 runs; costs no extra invocation.
  if (behavioral.length > 0) {
    const { status, observed } = evaluate(() => checkMutationScope(behavioral));
    results.push({
      id: "mutation-scope",
      tier: "2*",
      status,
      observed,
      costUsd: 0,
      durationMs: 0,
    });
    console.log(`· mutation-scope (derived) ... ${status}`);
  }

  writeFileSync(REPORT_PATH, renderReport(results, manualCases()));
  console.log(`\nReport written to evals/report.md`);

  const failed = results.filter((r) => r.status === "FAIL").length;
  process.exit(failed > 0 ? 1 : 0);
}

await main();
